const mirror = (square: number): number => (7 - (square >> 3)) * 8 + (square & 7);

export function nonPawnMaterial(board: Position["board"]): Record<Color, number> {
  const result: Record<Color, number> = { w: 0, b: 0 };
  for (const piece of board)
    if (piece && piece[1] !== "p" && piece[1] !== "k")
      result[piece[0] as Color] += VAL[piece[1] as PieceKind];
  return result;
}

export function evaluate(position: Position): number {
  let score = 0,
    material = 0,
    whiteKing = -1,
    blackKing = -1;
  for (let square = 0; square < 64; square++) {
    const piece = position.board[square];
    if (!piece) continue;
    const type = piece[1] as PieceKind;
    if (type === "k") {
      if (piece[0] === "w") whiteKing = square;
      else blackKing = square;
      continue;
    }
    if (type !== "p") material += VAL[type];
    if (piece[0] === "w") score += VAL[type] + PST[type][square];
    else score -= VAL[type] + PST[type][mirror(square)];
  }
  const kingTable = material <= 2600 ? PST.ke : PST.k;
  if (whiteKing >= 0) score += kingTable[whiteKing];
  if (blackKing >= 0) score -= kingTable[mirror(blackKing)];
  return score;
}
